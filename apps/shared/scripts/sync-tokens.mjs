// Copies the design tokens (:root block) and the self-hosted fonts from the web client,
// so the apps and the web client stay on one token set. Run before every build.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', '..', 'web', 'static');
const css = readFileSync(join(web, 'style.css'), 'utf8');
const start = css.indexOf(':root {');
if (start < 0) throw new Error('no :root block in web/static/style.css');
let depth = 0, end = -1;
for (let i = css.indexOf('{', start); i < css.length; i++) {
  if (css[i] === '{') depth++;
  else if (css[i] === '}' && --depth === 0) { end = i + 1; break; }
}
const fontFaces = css.slice(0, start).replace(/url\("fonts\//g, 'url("fonts/');
const out = join(here, '..', 'src', 'styles', 'tokens.gen.css');
writeFileSync(out, `/* GENERATED by scripts/sync-tokens.mjs from web/static/style.css – do not edit */\n${fontFaces}\n${css.slice(start, end)}\n`);

const fontsOut = join(here, '..', 'public', 'fonts');
mkdirSync(fontsOut, { recursive: true });
for (const f of readdirSync(join(web, 'fonts'))) copyFileSync(join(web, 'fonts', f), join(fontsOut, f));
console.log('tokens + fonts synced from web/static');
